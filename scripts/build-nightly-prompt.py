#!/usr/bin/env python3
"""Build prompts and PR bodies for the nightly plugin review workflow.

Usage:
  python3 scripts/build-nightly-prompt.py prompt <review-file>
      → prints the Claude fix prompt to stdout

  python3 scripts/build-nightly-prompt.py pr-body <review-file> <autofix-file>
      → prints the GitHub PR body to stdout
"""
import pathlib
import sys


def build_prompt(review_path: pathlib.Path) -> str:
    review = review_path.read_text()
    cwd = pathlib.Path.cwd()
    return f"""You are fixing plugin quality issues found in an automated nightly review.

Here is the review output:
{review}

Fix ALL WARN findings by directly editing the plugin files in the repository.

Rules:
- Fix only what the review explicitly flagged as WARN or FATAL
- Do not fix NOTEs (they are informational only)
- Do not add new agents, commands, or skills
- Read each affected file before editing it
- After all fixes are complete, output a summary titled "## Fixes Applied" listing each change

The plugin files are in: {cwd}/plugins/
"""


def build_pr_body(review_path: pathlib.Path, autofix_path: pathlib.Path) -> str:
    review = review_path.read_text()
    autofix = autofix_path.read_text()

    preview_lines = review.splitlines()[:80]
    preview = "\n".join(preview_lines)

    fixes_lines = []
    found = False
    for line in autofix.splitlines():
        if "## Fixes Applied" in line:
            found = True
        if found:
            fixes_lines.append(line)
    fixes = "\n".join(fixes_lines) if fixes_lines else "See workflow run for fix details."

    return (
        "Auto-generated by nightly semantic review. "
        "Merges automatically once fast-validate and validate-tier1 pass.\n\n"
        "## Review Findings\n\n"
        f"{preview}\n\n"
        f"{fixes}\n"
    )


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit("Usage: build-nightly-prompt.py prompt <review-file> | pr-body <review-file> <autofix-file>")

    mode = sys.argv[1]
    if mode == "prompt":
        print(build_prompt(pathlib.Path(sys.argv[2])))
    elif mode == "pr-body":
        if len(sys.argv) < 4:
            sys.exit("Usage: build-nightly-prompt.py pr-body <review-file> <autofix-file>")
        print(build_pr_body(pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])))
    else:
        sys.exit(f"Unknown mode: {mode}")
